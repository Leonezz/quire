import { describe, expect, it } from "vitest";

import { readerDocumentV2Schema } from "./reader-document-v2-contract";
import {
  anchorForTimeRange,
  dedupeRollingCues,
  formatTimestamp,
  normalizeTranscript,
  parseTranscriptCues,
  timeRangeForOffsets,
  validateRefinedTranscript,
} from "./transcript";

describe("transcript normalization engine", () => {
  it("parses WebVTT voice spans, inline karaoke tags, and entities", () => {
    const vtt = `WEBVTT

NOTE Generated by publisher

1
00:04:12.000 --> 00:04:18.500 align:start position:0%
<v Dwarkesh Patel>Let's start with <00:04:13.200><c>scaling</c> &amp; data walls.</v>

2
00:04:19.000 --> 00:04:21.000
[Music]

3
00:04:22.250 --> 00:04:29.000
<v Ilya Sutskever>Pre-training had one special property.</v>
`;

    const cues = parseTranscriptCues(vtt, "text/vtt");
    expect(cues).toEqual([
      {
        endSec: 258.5,
        speaker: "Dwarkesh Patel",
        startSec: 252,
        text: "Let's start with scaling & data walls.",
      },
      {
        endSec: 269,
        speaker: "Ilya Sutskever",
        startSec: 262.25,
        text: "Pre-training had one special property.",
      },
    ]);
  });

  it("parses Podcasting 2.0 JSON, Whisper verbose_json, and YouTube srv3 XML", () => {
    const podcastJson = JSON.stringify({
      segments: [
        { body: "Welcome to the show.", endTime: 4.5, speaker: "Host", startTime: 0.5 },
        { body: "Glad to be here.", endTime: 8.2, speaker: "Guest", startTime: 4.8 },
      ],
    });
    expect(parseTranscriptCues(podcastJson, "application/json")).toHaveLength(2);

    const whisperJson = JSON.stringify({
      segments: [{ end: 12.4, start: 3.1, text: "Local Whisper segment output." }],
    });
    expect(parseTranscriptCues(whisperJson)).toEqual([
      { endSec: 12.4, startSec: 3.1, text: "Local Whisper segment output." },
    ]);

    const srv3 = `<?xml version="1.0" encoding="utf-8" ?><timedtext format="3"><body>
      <p t="4120" d="3200"><s>Tokenization</s><s> is</s><s> weird.</s></p>
      <p t="7500" d="2000">   </p>
    </body></timedtext>`;
    expect(parseTranscriptCues(srv3, "text/xml")).toEqual([
      { endSec: 7.32, startSec: 4.12, text: "Tokenization is weird." },
    ]);
  });

  it("deduplicates rolling YouTube auto-caption overlaps cleanly", () => {
    const rolling = [
      { endSec: 4.0, startSec: 0.0, text: "pre training as we knew it" },
      { endSec: 4.1, startSec: 2.0, text: "pre training as we knew it" },
      { endSec: 6.5, startSec: 2.0, text: "pre training as we knew it had one special property" },
      { endSec: 9.2, startSec: 5.0, text: "one special property compute grew much faster" },
    ];
    const deduped = dedupeRollingCues(rolling);
    const mergedText = deduped.map((c) => c.text).join(" ");
    expect(mergedText).toBe("pre training as we knew it had one special property compute grew much faster");
  });

  it("builds conformant ReaderDocumentV2 with chapters, keyframes, and exact plain-text offsets", () => {
    const cues = [
      { endSec: 12, speaker: "Host", startSec: 0, text: "Welcome back to the podcast." },
      { endSec: 22, speaker: "Host", startSec: 12.3, text: "Today we examine byte-pair encoding." },
      { endSec: 38, speaker: "Guest", startSec: 24.0, text: "Models never see raw characters; they see integer token IDs." },
      { endSec: 75, speaker: "Guest", startSec: 60.0, text: "Now let us look at Python whitespace compression in cl100k." },
    ];
    const result = normalizeTranscript(cues, {
      chapters: [
        { startSec: 0, title: "Why Tokenization Matters" },
        { startSec: 60, title: "Whitespace Compression" },
      ],
      keyframes: [
        {
          caption: "00:24 · Slide 1 — Token IDs",
          height: 360,
          timeSec: 24,
          url: "quire-figure://0123456789abcdef/frame-24000.jpg",
          width: 640,
        },
      ],
      title: "Tokenizer Deep Dive",
    });

    expect(readerDocumentV2Schema.safeParse(result.document).success).toBe(true);
    expect(result.anchors).toHaveLength(3);

    // Every anchor's [start, end) slice in `plain` must match its rendered paragraph character-for-character
    expect(result.plain.slice(result.anchors[0]!.start, result.anchors[0]!.end)).toBe(
      "Welcome back to the podcast. Today we examine byte-pair encoding.",
    );
    expect(result.anchors[0]!.speaker).toBe("Host");
    expect(result.plain.slice(result.anchors[1]!.start, result.anchors[1]!.end)).toBe(
      "Models never see raw characters; they see integer token IDs.",
    );
    expect(result.anchors[1]!.speaker).toBe("Guest");

    // Dual-anchor lookup: quote offsets -> timeRange -> re-anchored paragraph
    const quote = "they see integer token IDs.";
    const quoteStart = result.plain.indexOf(quote);
    const quoteEnd = quoteStart + quote.length;
    const range = timeRangeForOffsets(result.anchors, quoteStart, quoteEnd);
    expect(range).toBeDefined();
    expect(range![0]).toBeGreaterThanOrEqual(24);
    expect(range![1]).toBeLessThanOrEqual(38);

    const recovered = anchorForTimeRange(result.anchors, range!);
    expect(recovered?.paragraphIndex).toBe(1);
    expect(formatTimestamp(60)).toBe("01:00");
  });

  it("splits unpunctuated auto-captions at natural pauses instead of producing a wall of text", () => {
    const unpunctuated = Array.from({ length: 24 }, (_, index) => ({
      endSec: index * 4 + 3.4,
      // Insert a clear 1.1s breathing pause after cue 14
      startSec: index * 4 + (index >= 15 ? 0.5 : 0),
      text: `segment ${index} carries an unpunctuated stream of automatic speech recognition words coming in fast`,
    }));
    const result = normalizeTranscript(unpunctuated);
    expect(result.anchors.length).toBeGreaterThanOrEqual(2);
  });

  it("enforces monotonicity and ±20% word-count guardrails on Agent-refined transcripts", () => {
    const raw = Array.from({ length: 10 }, (_, idx) => ({
      endSec: idx * 10 + 9.5,
      startSec: idx * 10,
      text: `observation ${idx} examines how neural scaling laws behave when organic internet tokens run out`,
    }));

    const faithfulMarkdown = [
      "## Scaling Laws and Organic Data",
      "[00:00] **Ilya Sutskever**: " +
        raw
          .slice(0, 5)
          .map((c) => `${c.text}.`)
          .join(" "),
      "[00:50] **Ilya Sutskever**: " +
        raw
          .slice(5)
          .map((c) => `${c.text}.`)
          .join(" "),
    ].join("\n\n");

    const okResult = validateRefinedTranscript(faithfulMarkdown, raw);
    expect(okResult.ok).toBe(true);

    // Summarized away (>20% shorter) must be rejected
    const lazySummary = "## Summary\n\n[00:00] **Ilya**: Scaling laws hit a token wall.";
    const rejected = validateRefinedTranscript(lazySummary, raw);
    expect(rejected.ok).toBe(false);
    if (!rejected.ok) {
      expect(rejected.issues.some((msg) => msg.includes("Word count drifted"))).toBe(true);
    }
  });
});
